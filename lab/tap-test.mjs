// Touch contract on phones: the browser scrolls the page; a tap on a control acts and does not move the page.
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright-core');
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true, args: ['--enable-gpu', '--ignore-gpu-blocklist'] });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
const p = await ctx.newPage(); const cdp = await ctx.newCDPSession(p);
await p.goto('http://localhost:4520/', { waitUntil: 'load' });
await p.waitForFunction(() => document.documentElement.classList.contains('gl-live'), null, { timeout: 30000 });
await p.waitForTimeout(1200);
const tapAt = async (x, y) => { await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y }] }); await p.waitForTimeout(60); await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] }); };
const jump = async (s) => { await p.evaluate((s) => document.querySelector(`.menu__link[data-jump="${s}"]`).click(), s); await p.waitForTimeout(600); };
const swipeOn = async (x, y0, y1) => { await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y: y0 }] }); for (let k = 1; k <= 8; k++) { await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x, y: y0 + ((y1 - y0) * k) / 8 }] }); await p.waitForTimeout(16); } await p.waitForTimeout(100); await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] }); await p.waitForTimeout(700); };
let fails = 0; const check = (l, ok, x = '') => { if (!ok) fails++; console.log(`  ${l.padEnd(58)} ${ok ? 'ok' : 'FAIL'}${x ? '  ' + x : ''}`); };
const y = () => p.evaluate(() => Math.round(scrollY));
let a = await y(); await swipeOn(195, 650, 420);
check('a swipe on the page scrolls it', (await y()) > a + 100, `moved ${(await y()) - a}`);
a = await y(); await swipeOn(195, 300, 120);
check('a swipe on the product band scrolls too', (await y()) > a + 80, `moved ${(await y()) - a}`);
await jump('how');
const before = await y(), st = await p.locator('#step-1').boundingBox();
await tapAt(st.x + st.width / 2, st.y + st.height / 2); await p.waitForTimeout(400);
check('tap on a step plays it', await p.evaluate(() => !!window.__sf.world.s3.tl && window.__sf.state.step === 1));
check('tap does not move the page', Math.abs((await y()) - before) < 2);
await p.waitForTimeout(1500);
await jump('customize');
const y1 = await y();
const sw = await p.locator('.swatch[data-color="sand"]').boundingBox();
await tapAt(sw.x + sw.width / 2, sw.y + sw.height / 2); await p.waitForTimeout(600);
check('tap on a swatch applies it', (await p.evaluate(() => window.__sf.state.color)) === 'sand');
const sz = await p.locator('.size[data-size="S"]').boundingBox();
await tapAt(sz.x + sz.width / 2, sz.y + sz.height / 2); await p.waitForFunction(() => window.__sf.world.slot.sizeId === 'S', null, { timeout: 8000 });
check('tap on a size swaps the model', (await p.evaluate(() => window.__sf.state.size)) === 'S');
check('taps do not move the page', Math.abs((await y()) - y1) < 2, `${(await y()) - y1}`);
const box = await p.evaluate(() => { const r = document.querySelector('[data-world]').getBoundingClientRect(); return { x: r.left + r.width / 2, y: r.top + r.height / 2 }; });
await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [box] });
for (let k = 1; k <= 10; k++) { await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: box.x + k * 14, y: box.y }] }); await p.waitForTimeout(16); }
const held = await p.evaluate(() => window.__sf.world.slot.drag.held);
await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] }); await p.waitForTimeout(300);
check('sideways on the band turns the product', held);
await jump('inside');
const lb = await p.locator('.layer-btn[data-layer="1"]').boundingBox();
await tapAt(lb.x + lb.width / 2, lb.y + lb.height / 2); await p.waitForTimeout(500);
check('tap on a layer opens the sheet', await p.evaluate(() => document.querySelector('[data-sheet]').classList.contains('is-open')));
await jump('customize');
check('leaving Inside closes the sheet', !(await p.evaluate(() => document.querySelector('[data-sheet]').classList.contains('is-open'))));
check('colour and size carried on', (await p.evaluate(() => `${window.__sf.state.color} ${window.__sf.world.slot.sizeId}`)) === 'sand S');
console.log(fails ? `FAILURES: ${fails}` : 'all touch checks passed');
await b.close();
